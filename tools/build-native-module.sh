#!/bin/sh
# Overlay and build the native RTW88 and MT7902 modules on FreeBSD.
set -eu

SRCROOT="${SRCROOT:-/usr/src}"
REPO_ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
OUTDIR="${OUTDIR:-$REPO_ROOT/build-native}"

if [ "$(uname -s)" != "FreeBSD" ]; then
    echo "This script must run on FreeBSD, not $(uname -s)." >&2
    exit 1
fi
if [ ! -d "$SRCROOT/sys/modules" ] || [ ! -d "$SRCROOT/sys/dev" ]; then
    echo "FreeBSD source tree not found at $SRCROOT (set SRCROOT)." >&2
    exit 1
fi

BUILD_ID="$(git -C "$REPO_ROOT" rev-parse --short=12 HEAD 2>/dev/null || echo source-unversioned)"
if ! git -C "$REPO_ROOT" diff --quiet -- \
    sys/dev/rtw88_native sys/modules/rtw88_native \
    sys/dev/mt76/mt7902 sys/modules/mt7902_native \
    sys/modules/ng_ubt_mt7902 tools/build-native-module.sh; then
    BUILD_ID="${BUILD_ID}-dirty"
fi

install -d "$SRCROOT/sys/dev/rtw88_native" \
    "$SRCROOT/sys/modules/rtw88_native" \
    "$SRCROOT/sys/dev/mt76/mt7902" \
    "$SRCROOT/sys/modules/mt7902_native" \
    "$SRCROOT/sys/modules/ng_ubt_mt7902"
cp -R "$REPO_ROOT/sys/dev/rtw88_native/." "$SRCROOT/sys/dev/rtw88_native/"
cp -R "$REPO_ROOT/sys/modules/rtw88_native/." "$SRCROOT/sys/modules/rtw88_native/"
cp -R "$REPO_ROOT/sys/dev/mt76/mt7902/." "$SRCROOT/sys/dev/mt76/mt7902/"
cp -R "$REPO_ROOT/sys/modules/mt7902_native/." "$SRCROOT/sys/modules/mt7902_native/"
cp -R "$REPO_ROOT/sys/modules/ng_ubt_mt7902/." "$SRCROOT/sys/modules/ng_ubt_mt7902/"

# Stamp the exact repository revision into RTW88 so dmesg makes stale
# /usr/src overlays and stale local checkouts obvious.
printf '%s\n' \
    '/* Generated by tools/build-native-module.sh; do not edit. */' \
    '#ifndef _RTW88_NATIVE_BUILD_H_' \
    '#define _RTW88_NATIVE_BUILD_H_' \
    "#define RTW88_NATIVE_BUILD_ID \"$BUILD_ID\"" \
    '#endif' > "$SRCROOT/sys/dev/rtw88_native/rtw88_native_build.h"
echo "Synced native RTW88 and MT7902 source revision $BUILD_ID into $SRCROOT"

# Build RTW88.
cd "$SRCROOT/sys/modules/rtw88_native"
RTW88_OBJDIR="$(make SRCTOP="$SRCROOT" -V .OBJDIR)"
make SRCTOP="$SRCROOT" clean
make SRCTOP="$SRCROOT"
RTW88_MODULE="$RTW88_OBJDIR/if_rtw88_native.ko"
if [ ! -s "$RTW88_MODULE" ]; then
    echo "RTW88 build did not produce $RTW88_MODULE" >&2
    exit 1
fi

# Build the native MT7902 Wi-Fi module from its standalone module entry point.
cd "$SRCROOT/sys/modules/mt7902_native"
MT7902_OBJDIR="$(make SRCTOP="$SRCROOT" -V .OBJDIR)"
make SRCTOP="$SRCROOT" clean
make SRCTOP="$SRCROOT"
MT7902_MODULE="$MT7902_OBJDIR/if_mt7902_native.ko"
if [ ! -s "$MT7902_MODULE" ]; then
    echo "MT7902 Wi-Fi build did not produce $MT7902_MODULE" >&2
    exit 1
fi

# Build the optional USB Bluetooth subclass from its own module directory.
cd "$SRCROOT/sys/modules/ng_ubt_mt7902"
BT_OBJDIR="$(make SRCTOP="$SRCROOT" -V .OBJDIR)"
make SRCTOP="$SRCROOT" clean
make SRCTOP="$SRCROOT"
BT_MODULE="$BT_OBJDIR/ng_ubt_mt7902.ko"
if [ ! -s "$BT_MODULE" ]; then
    echo "MT7902 Bluetooth build did not produce $BT_MODULE" >&2
    exit 1
fi

install -d "$OUTDIR"
cp "$RTW88_MODULE" "$OUTDIR/if_rtw88_native.ko"
cp "$MT7902_MODULE" "$OUTDIR/if_mt7902_native.ko"
cp "$BT_MODULE" "$OUTDIR/ng_ubt_mt7902.ko"
echo "Build succeeded:"
echo "  $OUTDIR/if_rtw88_native.ko"
echo "  $OUTDIR/if_mt7902_native.ko"
echo "  $OUTDIR/ng_ubt_mt7902.ko"
